// Writes ELEVENLABS.md: every prompt needed to record the game's audio, in the
// order you would work through them, each under the file name the game expects.
//
//   node scripts/build-prompts.mjs
//
// The prompts live in src/audio/manifest.js (sounds, music) and
// src/data/riders.js (voices, scripts). Edit those and run this again.
import { writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SFX, MUSIC } from '../src/audio/manifest.js';
import { VOICES, RIDERS, CAR_LINES, clipsOf } from '../src/data/riders.js';
import { POIS } from '../src/world/city.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = [];
const p = (...lines) => out.push(...lines);

const hourText = (h) => {
  const h24 = Math.floor(h) % 24, m = Math.round((h - Math.floor(h)) * 60);
  const h12 = h24 % 12 === 0 ? 12 : h24 % 12;
  return `${h12}${m ? `:${String(m).padStart(2, '0')}` : ''} ${h24 < 12 ? 'am' : 'pm'}`;
};
const mmss = (s) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;
const POI = { pier: 'Pier 7' };
for (const [id, name] of POIS) POI[id] = name;

const loops = SFX.filter((s) => s.loop), shots = SFX.filter((s) => !s.loop);
const riderVoices = Object.keys(VOICES).filter((v) => v !== 'nim');
const clipCount = RIDERS.reduce((n, r) => n + clipsOf(r).length, 0) + CAR_LINES.length;

/** A paragraph in a voice's own words, for the Voice Design preview. */
function sample(voiceId) {
  const lines = [];
  if (voiceId === 'nim') for (const l of CAR_LINES) lines.push(l.text);
  for (const r of RIDERS) if (r.id === voiceId) for (const [, text] of clipsOf(r)) lines.push(text);
  let text = '';
  for (const l of lines) {
    if (text.length > 260) break;
    text += (text ? ' ' : '') + l;
  }
  return text;
}

// ------------------------------------------------------------------ intro

p(
  '# ElevenLabs prompts for Fare Weather',
  '',
  '> Generated by `npm run prompts` from `src/audio/manifest.js` and `src/data/riders.js`. Edit those, not this file.',
  '',
  'Everything the game can play, with the prompt that makes it and the file name to save it under.',
  '',
  '## How it fits together',
  '',
  '- Save each recording under `public/audio/` with the path shown above its prompt, for example `public/audio/sfx/door_open.mp3`. The name is what links a file to its sound; the extension can be `.mp3`, `.wav`, `.m4a` or `.ogg`.',
  '- Raw takes can go through `npm run audio` instead, which trims them and evens out their volume: see "From takes to recordings" in the README.',
  '- Nothing is required. The game plays a built-in stand-in for every sound that has no recording yet, and shows voices as subtitles, so you can add files a few at a time and hear each one replace its stand-in.',
  '- With `npm run dev` running, the page reloads by itself when a file is added or removed.',
  '',
  `| What | How many | ElevenLabs tool | Goes in |`,
  `| --- | --- | --- | --- |`,
  `| Sound effects | ${SFX.length} (${loops.length} loops, ${shots.length} one-shots) | Sound Effects | \`public/audio/sfx/\` |`,
  `| Radio tracks | ${MUSIC.length} | Music | \`public/audio/music/\` |`,
  `| Voices to create | ${riderVoices.length + 1} | Voice Design | (stay in your ElevenLabs voice library) |`,
  `| Spoken clips | ${clipCount} | Text to Speech | \`public/audio/voice/\` |`,
  '',
  'A sensible order: a few loops first (`cabin_drive`, `rain_light`, `city_night`) because they are heard the most, then one radio track, then the car voice and one rider to check the voices sit well in the mix.',
  '',
);

// ------------------------------------------------------------------ sfx

p(
  '## 1. Sound effects',
  '',
  'Tool: **Sound Effects**, model **Eleven Text to Sound v3** where your account offers it, v2 otherwise. For each one set the duration and prompt influence given, and turn **Loop** on where it says so.',
  '',
  '- Generate a few takes and keep the plainest. A bed that draws attention to itself gets tiring after ten minutes.',
  '- The beds are written from inside a closed car on purpose. The game opens the street sound up by itself when a door lifts.',
  '- The prompts say what should be heard and never what should not: naming a sound, even to rule it out, tends to bring it in.',
  '- Counts are a wish, not a promise. Ask for one click or three notes and expect two or four; generate several takes and keep, or cut down, the one that is closest.',
  '- "Very quiet", "faint" and "tiny" are taken at their word: a bed asked for that way came back as near silence. Describe the sound at an ordinary level; the game turns it down.',
  '- Levels do not need to match: each sound has its own volume in `src/audio/manifest.js` (`gain`), and `npm run audio` levels each take to the stand-in it replaces.',
  '',
  '### Loops',
  '',
);
const sfxBlock = (s) => {
  p(
    `#### \`sfx/${s.id}.mp3\``,
    '',
    `${s.use}  `,
    `Duration **${s.seconds} s** · Loop **${s.loop ? 'on' : 'off'}** · Prompt influence **${Math.round(s.influence * 100)}%**`,
    '',
    '```text',
    s.prompt,
    '```',
    '',
  );
};
loops.forEach(sfxBlock);
p('### One-shots', '');
shots.forEach(sfxBlock);

// ------------------------------------------------------------------ music

p(
  '## 2. Radio',
  '',
  'Tool: **Music**, model **Music v2.5**, instrumental. Set the length shown (a little either way is fine).',
  '',
  '- The radio picks tracks to suit the weather and the hour, using the moods listed here.',
  '- Any other audio file you put in `public/audio/music/` joins the playlist under its file name, so you are not limited to these six.',
  '- Until there is at least one file in that folder, the game plays its own generated lo-fi.',
  '',
);
for (const m of MUSIC) {
  p(
    `#### \`music/${m.id}.mp3\` — "${m.title}"`,
    '',
    `Length **${mmss(m.seconds)}** · plays most in: ${m.mood.join(', ')}`,
    '',
    '```text',
    m.prompt,
    '```',
    '',
  );
}

// ------------------------------------------------------------------ voices

p(
  '## 3. Voices',
  '',
  `Tool: **Voice Design**. Create these ${riderVoices.length + 1} voices once and save them to your library; the scripts in the next section name them. Each has a description to paste as the prompt and a preview text in the character's own words, so you hear the voice doing what it will actually do.`,
  '',
  'Nim, the car, is in every ride, so it is worth taking the most care over. Library voices work too if you would rather pick than design: match the age, accent and energy in the description.',
  '',
  'Everyone in this city is a robot, the riders included, but nobody sounds like one. The descriptions are of the people they sound like: warm, ordinary voices, with no vocoder, no metallic edge and no processing.',
  '',
);
for (const id of ['nim', ...riderVoices]) {
  const v = VOICES[id];
  p(`#### ${v.name}${v.role ? ` (${v.role})` : ''}`, '', '```text', v.design, '```', '', 'Preview text:', '', '```text', sample(id), '```', '');
}

// ------------------------------------------------------------------ dialogue

p(
  '## 4. Spoken clips',
  '',
  'Tool: **Text to Speech**, model **Eleven v3** or **v4**. Every clip is one voice saying one short thing: nobody in the cab makes conversation.',
  '',
  '- Words in `[square brackets]` are delivery cues for the model (`[laughs]`, `[whispers]`, `[exhales]`). Leave them in. An ellipsis is a pause; CAPITALS are emphasis.',
  '- Keep each clip as one file, and trim long silences from its ends.',
  '- The lines are said to nobody in particular: under the breath, to the window. A take that sounds like an announcement is the wrong take.',
  '- A call is one side only: the rider talks into a phone, and the gaps between the clips are the other end talking.',
  '- If a take sounds read rather than said, generate again before changing the words.',
  '',
  '### The car on its own',
  '',
  'Voice: **Nim**. Short lines the car says by itself: to riders with no script of their own, about the weather, when it is held up. One file each.',
  '',
  '| File | Said | Line |',
  '| --- | --- | --- |',
);
const WHEN = {
  welcome: 'a rider gets in', welcome_night: 'a rider gets in, evening', welcome_morning: 'a rider gets in, morning', depart: 'setting off',
  near: 'nearly there', arrive: 'at the destination', bye: 'a rider has left', rain: 'in rain', storm: 'in a storm', fog: 'in fog', snow: 'in snow',
  crossing: 'waiting for someone on a crossing', light: 'stopped at a red light',
};
for (const l of CAR_LINES) p(`| \`voice/car/${l.id}.mp3\` | ${WHEN[l.when] || l.when} | ${l.text} |`);
p('');

p('### Riders', '', 'One robot to a ride. Each says something as they get in, a few short things on the way, well apart, and something as they get out. One file each, in the voice of that name.', '');
for (const r of RIDERS) {
  const when = r.hours ? `rides between ${hourText(r.hours[0])} and ${hourText(r.hours[1])}` : 'rides at any hour';
  const way = r.call ? 'on the way, into a phone' : 'on the way';
  p(`#### ${VOICES[r.id].name}`, '', `${POI[r.from]} to ${POI[r.to]}, ${when}. ${r.memory}`, '', '| File | Said | Line |', '| --- | --- | --- |');
  for (const [clip, text] of clipsOf(r)) p(`| \`voice/${r.id}/${clip}.mp3\` | ${clip === 'hello' ? 'getting in' : clip === 'bye' ? 'getting out' : way} | ${text} |`);
  p('');
}

// ------------------------------------------------------------------ checklist

p('## Checklist', '', 'Every file the game looks for, under `public/audio/`:', '', '```text');
for (const s of SFX) p(`sfx/${s.id}.mp3`);
for (const m of MUSIC) p(`music/${m.id}.mp3`);
for (const l of CAR_LINES) p(`voice/car/${l.id}.mp3`);
for (const r of RIDERS) for (const [c] of clipsOf(r)) p(`voice/${r.id}/${c}.mp3`);
p('```', '');

// sanity: every rider has a voice, and every line is short enough to be a remark
const tooLong = RIDERS.flatMap((r) => clipsOf(r).map(([c, text]) => [`${r.id}/${c}`, text.length])).filter(([, n]) => n > 90);
if (tooLong.length) throw new Error(`lines over 90 characters: ${tooLong.map(([k, n]) => `${k} (${n})`).join(', ')}`);
const unknown = RIDERS.map((r) => r.id).filter((w) => !VOICES[w]);
if (unknown.length) throw new Error(`riders with no voice of their name: ${unknown.join(', ')}`);
const noPoi = RIDERS.filter((r) => !POI[r.from] || !POI[r.to]);
if (noPoi.length) throw new Error(`riders with unknown places: ${noPoi.map((r) => r.id).join(', ')}`);

await writeFile(join(root, 'ELEVENLABS.md'), out.join('\n'));
console.log(`ELEVENLABS.md: ${SFX.length} sound effects, ${MUSIC.length} tracks, ${riderVoices.length + 1} voices, ${clipCount} spoken clips`);
